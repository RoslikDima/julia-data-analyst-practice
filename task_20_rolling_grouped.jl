# Задача 20 (Модуль 6, Задача 2): Групповой расчет 2-дневного скользящего среднего
#
# Условие задачи:
# 1. Задан датафрейм pharmacy_daily с ежедневной выручкой двух аптек.
# 2. Через @chain:
#    - Отсортировать данные по аптеке и дате продажи.
#    - Сгруппировать по pharmacy (groupby).
#    - Рассчитать 2-дневное скользящее среднее ma2_revenue через lag.
# 3. Сохранить результат в pharmacy_smoothed и вывести таблицу.
# ==============================================================================

# Авторское решение (Dima Roslik):
using DataFrames, Chain, Dates, ShiftedArrays
using ShiftedArrays: lag

pharmacy_daily = DataFrame(
    pharmacy = ["Аптека №1", "Аптека №2", "Аптека №1", "Аптека №2", "Аптека №1", "Аптека №2", "Аптека №1", "Аптека №2"],
    sale_date = [
        Date(2024, 2, 1), Date(2024, 2, 1),
        Date(2024, 2, 3), Date(2024, 2, 2),
        Date(2024, 2, 2), Date(2024, 2, 4),
        Date(2024, 2, 4), Date(2024, 2, 3)
    ],
    revenue = [100000.0, 80000.0, 120000.0, 95000.0, 110000.0, 130000.0, 140000.0, 110000.0]
)

pharmacy_smoothed = @chain pharmacy_daily begin
    sort([:pharmacy, :sale_date])
    groupby(:pharmacy)
    transform(:revenue => (r -> (r .+ lag(r, 1)) ./ 2) => :ma2_revenue)
end

println("Групповое скользящее среднее выручки:")
println(pharmacy_smoothed)
