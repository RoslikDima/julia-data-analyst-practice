# Задача 2: Пользовательская функция и векторный скоринг
#
# Условие задачи:
# orders = [150.0, 520.0, 499.0, 1200.0, 80.0]
# 1. Написать функцию categorize_order(amount), возвращающую:
#    "Крупный" при amount >= 500 и "Стандартный" при amount < 500
# 2. Применить функцию к вектору orders через точку (.) и сохранить в result
# ==============================================================================

# Авторское решение (Dima Roslik):
orders = [150.0, 520.0, 499.0, 1200.0, 80.0]

function categorize_order(amount)
    amount >= 500 ? "Крупный" : "Стандартный"
end

result = categorize_order.(orders)
println("Категории заказов: ", result)
