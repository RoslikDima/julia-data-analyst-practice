# Условие задачи:
# drugs = ["аспирин", "НО-ШПА", "ибупрофен", "Кеторол", "парацетамол"]
# 1. С помощью map и блока do ... end привести все названия к нижнему регистру
#    через lowercase(...). Сохранить в normalized_drugs.
# 2. Отсортировать по длине названия (от коротких к длинным) через
#    sort(..., by = x -> length(x)).
# 3. Сохранить в sorted_drugs и вывести результат.
# ==============================================================================

# Авторское решение (Dima Roslik):
drugs = ["аспирин", "НО-ШПА", "ибупрофен", "Кеторол", "парацетамол"]

normalized_drugs = map(drugs) do x
    lowercase(x)
end

sorted_drugs = sort(normalized_drugs, by = x -> length(x))

println("Отсортированный список препаратов:")
println(sorted_drugs)
