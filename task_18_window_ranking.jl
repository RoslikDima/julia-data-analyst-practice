# Задача 18 (Модуль 5, Задача 3): Оконное ранжирование и расчет долей внутри групп
#
# Условие задачи:
# 1. Задан датафрейм rep_sales с продажами медпредов по регионам.
# 2. Через @chain:
#    - Отсортировать строки: регион (по возрастанию), продажи (по убыванию).
#    - Сгруппировать по region (groupby).
#    - Присвоить ранг rank_in_region через 1:length(v).
#    - Рассчитать pct_region_sales как долю от суммарных продаж региона.
# 3. Сохранить результат в rep_ranked и вывести таблицу.
# ==============================================================================

# Авторское решение (Dima Roslik):
using DataFrames, Chain

rep_sales = DataFrame(
    region = ["Центр", "Центр", "Центр", "Северо-Запад", "Северо-Запад", "Северо-Запад"],
    rep_name = ["Иванов", "Петров", "Сидоров", "Смирнов", "Кузнецов", "Попов"],
    sales = [3400000.0, 4100000.0, 2800000.0, 1900000.0, 2600000.0, 2200000.0]
)

rep_ranked = @chain rep_sales begin
    sort([:region, order(:sales, rev=true)])
    groupby(:region)
    transform(:sales => (v -> 1:length(v)) => :rank_in_region)
    transform(:sales => (v -> (v ./ sum(v)) .* 100) => :pct_region_sales)
end

println("Рейтинг медпредов по регионам:")
println(rep_ranked)
