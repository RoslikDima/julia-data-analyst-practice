# Задача 7 (Лямбды, Задача 1): Фильтрация и поэлементная трансформация
#
# Условие задачи:
# losses = [150.0, 0.0, 480.0, 1200.0, 0.0, 310.0, 750.0]
# 1. С помощью filter и анонимной функции x -> ... отобрать ненулевые списания (> 0.0).
#    Сохранить результат в active_losses.
# 2. С помощью map и анонимной функции применить скидку 10% (умножить на 0.9)
#    и округлить round(...) каждый элемент.
# 3. Сохранить в discounted_losses и вывести результат.
# ==============================================================================

# Авторское решение (Dima Roslik):
losses = [150.0, 0.0, 480.0, 1200.0, 0.0, 310.0, 750.0]

active_losses = filter(x -> x > 0.0, losses)

discounted_losses = map(x -> round(x * 0.9), active_losses)

println("Результат после фильтрации и дисконтирования:")
println(discounted_losses)
